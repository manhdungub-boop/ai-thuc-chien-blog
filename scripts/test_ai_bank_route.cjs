'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const pageFile = 'ngan-hang-ai.html';
const pagePath = path.join(root, pageFile);
assert.ok(fs.existsSync(pagePath), 'Ngân hàng AI source page must exist');
const html = fs.readFileSync(pagePath, 'utf8');
assert.match(html, /<title>Ngân hàng AI/i, 'AI Bank page title must be present');
assert.match(html, /rel="canonical" href="https:\/\/ai-thuc-chien-blog\.manhdungub\.workers\.dev\/ngan-hang-ai\.html"/, 'AI Bank canonical must point to production canonical');
assert.match(html, /fetch\('\/data\/ai-tools\.json'/, 'AI Bank page must load the JSON catalog');
assert.match(html, /DUNG - AI/, 'AI Bank attribution must be preserved');
const builder = fs.readFileSync(path.join(root, 'scripts', 'build_static_site.cjs'), 'utf8');
assert.match(builder, /['"]ngan-hang-ai\.html['"]/, 'static builder must include AI Bank page in root assets');
assert.match(builder, /path\.join\(output,\s*['"]ngan-hang-ai\.html['"]\)/, 'static builder must verify AI Bank output using its output directory');
const seo = fs.readFileSync(path.join(root, 'scripts', 'generate_seo_feeds.cjs'), 'utf8');
assert.match(seo, /ngan-hang-ai\.html/, 'SEO feed generator must include AI Bank page');
const deploy = fs.readFileSync(path.join(root, '.github', 'workflows', 'deploy-preview-worker.yml'), 'utf8');
assert.match(deploy, /ngan-hang-ai\.html/, 'Preview deployment path filter must include AI Bank page');
assert.match(deploy, /data\/\*\*/, 'Preview deployment path filter must include catalog data');
const dist = path.join(root, 'dist', pageFile);
assert.ok(fs.existsSync(dist), 'AI Bank page must exist in dist after build');
const outputHtml = fs.readFileSync(dist, 'utf8');
assert.match(outputHtml, /fetch\('\/data\/ai-tools\.json'/, 'built AI Bank page must still fetch catalog');
assert.ok(fs.existsSync(path.join(root, 'dist', 'data', 'ai-tools.json')), 'catalog JSON must be copied to dist/data');
const sitemap = fs.readFileSync(path.join(root, 'dist', 'sitemap.xml'), 'utf8');
assert.match(sitemap, /<loc>https:\/\/ai-thuc-chien-blog\.manhdungub\.workers\.dev\/ngan-hang-ai\.html<\/loc>/, 'AI Bank canonical must be present in sitemap');
console.log('AI BANK ROUTE REGRESSION PASS: source, built HTML, JSON catalog asset, Preview trigger and sitemap entry.');
