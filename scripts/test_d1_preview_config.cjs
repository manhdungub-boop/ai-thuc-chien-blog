#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const config = JSON.parse(fs.readFileSync('wrangler.jsonc', 'utf8'));
const production = (config.d1_databases || []).filter(x => x.binding === 'DB');
const previews = ((config.previews || {}).d1_databases || []).filter(x => x.binding === 'DB');
assert.equal(production.length, 1, 'exactly one production DB binding named DB is required');
assert.equal(previews.length, 1, 'exactly one preview DB override named DB is required');
const prod = production[0];
const preview = previews[0];
assert.equal(prod.database_name, 'ai-thuc-chien-community', 'production database name changed unexpectedly');
assert.equal(preview.database_name, 'ai-thuc-chien-community-preview', 'preview database must be explicitly named as non-production');
const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
assert.match(prod.database_id || '', uuid, 'production D1 ID must be a UUID');
assert.match(preview.database_id || '', uuid, 'preview D1 ID must be a UUID');
assert.notEqual(prod.database_id, preview.database_id, 'preview D1 must never point to the production database');
assert.notEqual(prod.database_name, preview.database_name, 'preview D1 must never reuse the production database name');
const migrationConfig = JSON.parse(fs.readFileSync('wrangler.preview-migrations.jsonc', 'utf8'));
assert.equal(migrationConfig.account_id, config.account_id, 'preview migration account must match the Worker account');
const migrationDatabases = migrationConfig.d1_databases || [];
assert.equal(migrationDatabases.length, 1, 'preview migration config must contain exactly one database');
const migrationDb = migrationDatabases[0];
assert.equal(migrationDb.binding, 'PREVIEW_DB', 'preview migration must use a dedicated PREVIEW_DB binding');
assert.equal(migrationDb.database_id, preview.database_id, 'preview migration ID must match Worker preview ID');
assert.equal(migrationDb.database_name, preview.database_name, 'preview migration name must match Worker preview name');
assert.equal(migrationDb.migrations_dir, 'migrations', 'preview migration directory must be explicit');
assert.notEqual(migrationDb.database_id, prod.database_id, 'preview migration must never target production D1');
const productionDeployWorkflow = fs.readFileSync('.github/workflows/deploy-cloudflare-workers.yml', 'utf8');
assert.match(productionDeployWorkflow, /github\.event_name == 'workflow_dispatch' && github\.ref == 'refs\/heads\/main' && inputs\.confirm_production_worker_and_d1_changes == true/, 'Production deployment must require explicit manual confirmation from main');
assert.doesNotMatch(productionDeployWorkflow, /--request POST/, 'Production deployment must never create a D1 database automatically');
assert.match(productionDeployWorkflow, /fc2517cb-9543-4d7b-98f4-bcd5f3c013e7/, 'Production deploy must verify the exact reviewed D1 ID');
assert.match(productionDeployWorkflow, /d1 migrations apply/, 'D1 migrations remain available only behind the manual deploy job gate');
console.log('PASS: Production deploy is main-only, manually confirmed, and cannot auto-create a D1 database.');
console.log('PASS: production and preview D1 bindings are isolated; migration config matches the verified preview DB.');
